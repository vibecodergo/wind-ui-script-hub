"""Embed the converted, user-selected GIF sheet for a standalone executor script."""
from pathlib import Path
import base64

repo = Path(__file__).resolve().parents[1]
png = (repo / "assets/giphy-TrVla4Z2PYEkU.png").read_bytes()
encoded = base64.b64encode(png).decode("ascii")
source = '''-- Generated by build/giphy-background.py from assets/giphy-TrVla4Z2PYEkU.png.
-- Source: https://media4.giphy.com/media/TrVla4Z2PYEkU/giphy.gif
-- 16 frames at 10 FPS; 4x4 grid; 250x140 per frame; full 1.6-second animation.
local asset = getcustomasset or getsynasset
assert(type(asset) == "function" and type(writefile) == "function",
    "This background needs getcustomasset and writefile in your executor")
local path = "WindUI/assets/giphy-TrVla4Z2PYEkU-sheet.png"
if not (isfile and isfile(path)) then
    if makefolder and isfolder then
        if not isfolder("WindUI") then makefolder("WindUI") end
        if not isfolder("WindUI/assets") then makefolder("WindUI/assets") end
    end
    local encoded = [[ENCODED]]
    local alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
    local lookup, chunks = {}, {}
    for index = 1, #alphabet do lookup[alphabet:byte(index)] = index - 1 end
    for index = 1, #encoded, 4 do
        local a, b, c, d = encoded:byte(index, index + 3)
        local value = (lookup[a] or 0) * 262144 + (lookup[b] or 0) * 4096
            + (lookup[c] or 0) * 64 + (lookup[d] or 0)
        local chunk = string.char(math.floor(value / 65536) % 256, math.floor(value / 256) % 256, value % 256)
        chunks[#chunks + 1] = chunk:sub(1, c == 61 and 1 or d == 61 and 2 or 3)
    end
    local decoded = table.concat(chunks)
    assert(#decoded == BYTE_COUNT and decoded:sub(1, 8) == "\\137PNG\\13\\10\\26\\10", "Invalid embedded background")
    writefile(path, decoded)
end
return {
    Enabled = true, Type = "SpriteSheet", Asset = asset(path),
    FrameSize = Vector2.new(250, 140), Columns = 4, Rows = 4, FrameCount = 16,
    FPS = 10, Transparency = 0.6, Loop = true,
}
'''.replace("ENCODED", encoded).replace("BYTE_COUNT", str(len(png)))
(repo / "examples/GiphyBackground.lua").write_text(source, encoding="utf-8")
print(f"Embedded {len(png)} PNG bytes; no Roblox upload or runtime GIF decoding needed.")
